#!/usr/bin/env python3
"""Experiment registry: regenerates EXPERIMENTS.md from the results on disk.

Rerun after each eval, so the doc stays in sync with what actually ran.

  python registry.py
"""
import json, re, sys
from collections import defaultdict
from datetime import datetime
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "results" / "first_combat"
sys.path.insert(0, str(ROOT / "src"))
from stsenv.decks import ARCHETYPES, ENCOUNTERS  # noqa: E402
from convergence import table as convergence_table  # noqa: E402

# Display labels for result keys that are stored in French in the shipped JSON files.
LABELS = {"optimal (pioche connue)": "optimal (known draw order)"}


def variant(run):
    return re.sub(r"_s\d+$", "", run)


def read_experiment(d):
    """-> dict describing one experiment (one results folder), or None."""
    runs = [p for p in sorted(d.iterdir()) if p.is_dir() and (p / "config.json").exists()]
    if not runs:
        return None
    cfgs = [json.load(open(p / "config.json")) for p in runs]
    evals = {}
    for f in d.glob("eval*.json"):
        pool = f.stem.replace("eval", "").lstrip("_") or "—"
        evals[pool] = json.load(open(f))
    c0 = cfgs[0]
    return {"dir": d.name, "deck": c0.get("deck", "—"), "encounter": c0.get("encounter") or "seed 4",
            "extra": c0.get("extra_cards", 0), "steps": c0.get("steps"), "n_runs": len(runs),
            "algos": sorted({c["algo"] for c in cfgs}),
            "encodings": sorted({c.get("encoding", "onehot") for c in cfgs}),
            "seeds": sorted({c["seed"] for c in cfgs}), "evals": evals,
            "behavior": {f.stem.split("_", 1)[1]: json.load(open(f)) for f in d.glob("behavior_*.json")},
            "mtime": max(p.stat().st_mtime for p in runs)}


def variant_table(ev):
    finals = defaultdict(list)
    for run, rows in ev["runs"].items():
        finals[variant(run)].append(rows[-1]["hp_lost"])
    return {v: float(np.mean(x)) for v, x in sorted(finals.items(), key=lambda kv: np.mean(kv[1]))}


def main():
    exps = [e for e in (read_experiment(d) for d in sorted(RES.iterdir()) if d.is_dir()) if e]
    exps.sort(key=lambda e: e["mtime"])
    out = ["# Experiment registry",
           "",
           f"Regenerated by `experiments/first_combat/registry.py` on "
           f"{datetime.now():%Y-%m-%d %H:%M}. Metric: **HP lost per combat** (greedy eval, "
           f"paired seeds), averaged over training seeds.",
           ""]
    for e in exps:
        title = f"## `{e['dir']}` — deck *{e['deck']}* vs *{e['encounter']}*"
        out += [title, ""]
        q = ARCHETYPES.get(e["deck"], {}).get("question")
        if q:
            out += [f"**Question**: {q}", ""]
        out += [f"- {e['n_runs']} runs: {'/'.join(e['algos'])} × {'/'.join(e['encodings'])} × "
                f"{len(e['seeds'])} seeds, {e['steps']:,} steps".replace(",", " "),
                f"- {e['extra']} cards drawn per episode" if e["extra"] else "- fixed deck", ""]
        for pool, ev in sorted(e["evals"].items()):
            ref = ev.get("baselines", {})
            label = {"eval": "cards NEVER seen", "train": "cards seen in training"}.get(pool, pool)
            out += [f"**Eval — {label}** ({ev.get('n_eval', '?')} seeds)", ""]
            out += ["| policy | HP lost |", "|---|---|"]
            for v, hp in variant_table(ev).items():
                out.append(f"| {v} | {hp:.2f} |")
            for k in ("optimal (pioche connue)", "mcts_oracle@2000", "heuristic", "random"):
                if k in ref:
                    out.append(f"| *{LABELS.get(k, k)}* | *{ref[k]['hp_lost']:.2f}* |")
            out.append("")
        conv = convergence_table(RES / e["dir"], "train")
        if conv:
            out += ["**Convergence** (95% of the gain; 4 runs in parallel, pessimistic times)", "",
                    "| variant | steps | combats | steps/s | time | ms/step |", "|---|---|---|---|---|---|"]
            for r in conv:
                out.append(f"| {r['variant']} | {r['steps']:,} | {r['combats']:.0f} | {r['steps_per_s']:.0f} | "
                           f"{r['minutes']:.1f} min | {r['ms_per_step']:.2f} |".replace(",", " "))
            out.append("")
        for pool, beh in sorted(e["behavior"].items()):
            out += [f"**Behavior — {pool} cards**", "",
                    "| policy | HP lost | " + " | ".join(
                        k for k in next(iter(beh.values())) if k != "hp_lost") + " |",
                    "|" + "---|" * (2 + len(next(iter(beh.values()))) - 1)]
            for k, v in beh.items():
                cells = []
                for m, val in v.items():
                    if m == "hp_lost":
                        continue
                    x, n = val if isinstance(val, list) else (val, 0)
                    cells.append("—" if n == 0 or x != x else f"{x:.2f} ({n})")
                out.append(f"| {k} | {v['hp_lost']:.2f} | " + " | ".join(cells) + " |")
            out.append("")
    (ROOT / "EXPERIMENTS.md").write_text("\n".join(out) + "\n")
    print(f"{len(exps)} experiments -> {ROOT / 'EXPERIMENTS.md'}")


if __name__ == "__main__":
    main()
